import requests

from .config import Settings


class OllamaClient:

    def __init__(self, settings=None):
        self.settings = settings or Settings()

    def generate(self, model: str = "", prompt: str = "", parameters: dict | None = None, **kwargs) -> str:
        model = model or kwargs.get("model", "")
        prompt = prompt or kwargs.get("prompt", "")
        options = {"temperature": 0.1, "num_predict": 512}
        if parameters:
            options.update(parameters)
        try:
            response = requests.post(
                self.settings.ollama_url.rstrip("/") + "/api/generate",
                json={
                    "model": model,
                    "prompt": prompt,
                    "stream": False,
                    "options": options,
                },
                timeout=self.settings.timeout,
            )

            response.raise_for_status()

            data = response.json()

        except requests.RequestException as exc:
            raise RuntimeError(
                "Ollama is unavailable. "
                "Start Ollama and verify the configured model."
            ) from exc

        answer = data.get("response")

        if not isinstance(answer, str):
            raise RuntimeError(
                "Ollama returned an invalid response."
            )

        answer = answer.strip()

        if not answer:
            raise RuntimeError(
                "Ollama returned an empty response."
            )

        return self._clean_response(answer)

    @staticmethod
    def _clean_response(answer: str) -> str:
        """
        Remove obvious chat-continuation prefixes generated by
        small instruction/chat models.

        This does NOT attempt to rewrite the model's answer.
        """

        unwanted_prefixes = [
            "Assistant:",
            "AI:",
            "ASSISTANT:",
        ]

        changed = True

        while changed:
            changed = False

            for prefix in unwanted_prefixes:
                if answer.startswith(prefix):
                    answer = answer[len(prefix):].strip()
                    changed = True

        return answer