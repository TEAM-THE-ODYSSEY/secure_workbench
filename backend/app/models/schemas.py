"""
Pydantic v2 schemas for Main AI Agent.
Includes input task payload, planning schema, evidence chunk models,
structured reasoning output, execution trace record, and final response API model.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class TaskRequest(BaseModel):
    """Input payload for Main AI Agent task."""
    task_type: str = Field(default="REASONING", description="Task type (e.g. REASONING, GENERATE_PDF)")
    objective: str = Field(..., description="Natural language objective or user request")
    entities: List[str] = Field(default_factory=list, description="Target entity IDs/names e.g. EQ-P101A")
    document_type: Optional[str] = Field(default=None, description="Optional document type filter")
    version_constraint: Optional[str] = Field(default=None, description="Optional version constraint")
    allow_fallback: bool = Field(default=True, description="Allow fallback model or direct synthesis")


class Citation(BaseModel):
    """Source reference mapping claims to retrieved evidence."""
    document_id: str
    title: str
    version: str = "1.0"
    section: Optional[str] = None
    page: Optional[int] = None
    trust_level: str = "TRUSTED"
    snippet: Optional[str] = None


class EvidenceChunk(BaseModel):
    """Structured evidence chunk retrieved by KnowledgeTool or PIDTool."""
    document_id: str
    title: str
    version: str
    section: str
    page: Optional[int] = None
    entity_id: Optional[str] = None
    trust_level: str = "TRUSTED"
    content: str
    citation: Citation


class ProcedureStep(BaseModel):
    """Numbered procedural instruction step."""
    step_number: int
    instruction: str
    citations: List[Citation] = Field(default_factory=list)


class OperatingLimit(BaseModel):
    """Equipment or operational boundary parameters."""
    parameter: str
    value: str
    citations: List[Citation] = Field(default_factory=list)


class StructuredPDFContent(BaseModel):
    """Strict schema for verified ReportLab PDF generation."""
    title: str
    purpose: str
    scope: str
    preconditions: List[str] = Field(default_factory=list)
    safety_requirements: List[str] = Field(default_factory=list)
    procedure_steps: List[ProcedureStep] = Field(default_factory=list)
    operating_limits: List[OperatingLimit] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)
    references: List[Citation] = Field(default_factory=list)


class ContextPlan(BaseModel):
    """LLM Generation #1: Context requirement plan generated by Main Agent."""
    intent: str = Field(..., description="Identified user intent e.g. FAILURE_ANALYSIS, TOPOLOGY_QUERY, SOP_SYNTHESIS")
    entities: List[str] = Field(default_factory=list, description="Extracted entity tags e.g. P-101A, XV-101")
    required_context: List[str] = Field(
        default_factory=list,
        description="Target evidence domains e.g. ['equipment_spec', 'maintenance_history', 'sop', 'pid_topology']"
    )
    tool_calls: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of capability tool calls to make e.g. [{'tool': 'knowledge_search', 'query': 'P-101A SOP'}]"
    )
    output_type: str = Field(default="TEXT", description="Expected output format: TEXT or PDF")


class FinalReasoningOutput(BaseModel):
    """LLM Generation #2: Structured output produced by local reasoning LLM."""
    answer: str = Field(..., description="Comprehensive evidence-grounded answer")
    claims: List[str] = Field(default_factory=list, description="Key factual claims")
    citations: List[Citation] = Field(default_factory=list, description="Direct citations to evidence")
    confidence: str = Field(default="HIGH", description="Confidence rating: HIGH, MEDIUM, LOW")
    limitations: List[str] = Field(default_factory=list, description="Uncertainties or missing evidence notes")
    structured_pdf: Optional[StructuredPDFContent] = Field(default=None, description="Optional PDF content schema")


class ArtifactMetadata(BaseModel):
    """Persistent storage metadata for generated PDF or data artifact."""
    filename: str
    content_type: str = "application/pdf"
    storage_uri: Optional[str] = None
    file_size_bytes: int = 0
    bucket: Optional[str] = "trusted"


class ExecutionTraceRecord(BaseModel):
    """Safe execution trace and performance metrics for Main Agent task."""
    task_id: str
    intent: str
    entities: List[str] = Field(default_factory=list)
    tools_called: List[str] = Field(default_factory=list)
    evidence_count: int = 0
    active_model: str
    fallback_used: bool = False
    verification: str = "PASSED"
    latency_ms: float = 0.0
    latency_breakdown: Dict[str, float] = Field(default_factory=dict)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class AgentTaskResult(BaseModel):
    """Final response returned by Main AI Agent to client / API."""
    task_id: str
    status: str  # COMPLETE, INSUFFICIENT_EVIDENCE, VERIFICATION_FAILED, PDF_GENERATION_FAILED, MODEL_ERROR
    result_type: str = "TEXT"  # TEXT or PDF
    answer: Optional[str] = None
    artifact: Optional[ArtifactMetadata] = None
    model: str = "Qwen3-4B"
    fallback_used: bool = False
    citations: List[Citation] = Field(default_factory=list)
    message: Optional[str] = None
    structured_content: Optional[StructuredPDFContent] = None
    trace: Optional[ExecutionTraceRecord] = None
